<?php

namespace App\Modules\Treasury\Infrastructure\Models;

use Database\Factories\TitheFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\UseFactory;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;

/**
 * A tithe: what a member tithed on a day, in each currency. Not income of the church: it never
 * touches Accounting and is never sealed. The member belongs to Members and is read through the
 * MemberDirectory contract. Week and month keys are generated by the database. Never physically
 * deleted: the trash can be restored.
 *
 * @property string $id UUIDv7
 * @property int|null $legacy_id
 * @property Carbon $tithe_date
 * @property string $member_id
 * @property string $amount_ves
 * @property string $amount_usd
 * @property string $amount_cop
 * @property string|null $notes
 * @property string $week_key
 * @property string $month_key
 * @property string|null $created_by
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property Carbon|null $deleted_at
 */
#[Fillable(['tithe_date', 'member_id', 'amount_ves', 'amount_usd', 'amount_cop', 'notes'])]
#[UseFactory(TitheFactory::class)]
class Tithe extends Model
{
    /** @use HasFactory<TitheFactory> */
    use HasFactory;

    use HasUuids;
    use SoftDeletes;

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'legacy_id' => 'integer',
            'tithe_date' => 'date',
        ];
    }
}
