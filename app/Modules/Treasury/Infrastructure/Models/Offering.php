<?php

namespace App\Modules\Treasury\Infrastructure\Models;

use Database\Factories\OfferingFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\UseFactory;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;

/**
 * An offering. The giver is a member of the registry known by id (or nobody: anonymous); week
 * and month keys are generated by the database. Never physically deleted.
 *
 * @property string $id UUIDv7
 * @property int|null $legacy_id
 * @property Carbon $offering_date
 * @property string|null $member_id
 * @property string $offering_category_id
 * @property string|null $concept
 * @property string $amount_ves
 * @property string $amount_usd
 * @property string $amount_cop
 * @property string $week_key
 * @property string $month_key
 * @property string|null $created_by
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property Carbon|null $deleted_at
 * @property-read OfferingCategory $category
 */
#[Fillable(['offering_date', 'member_id', 'offering_category_id', 'concept', 'amount_ves', 'amount_usd', 'amount_cop'])]
#[UseFactory(OfferingFactory::class)]
class Offering extends Model
{
    /** @use HasFactory<OfferingFactory> */
    use HasFactory;

    use HasUuids;
    use SoftDeletes;

    /**
     * @return BelongsTo<OfferingCategory, $this>
     */
    public function category(): BelongsTo
    {
        return $this->belongsTo(OfferingCategory::class, 'offering_category_id');
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'legacy_id' => 'integer',
            'offering_date' => 'date',
        ];
    }
}
