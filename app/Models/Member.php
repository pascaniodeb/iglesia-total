<?php

namespace App\Models;

use App\Enums\MemberDocumentType;
use App\Enums\MemberEducationLevel;
use App\Enums\MemberMaritalStatus;
use App\Enums\MemberSex;
use App\Enums\MemberStatus;
use Database\Factories\MemberFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;

/**
 * @property string $id UUIDv7
 * @property int|null $legacy_id
 * @property string $full_name
 * @property MemberDocumentType|null $document_type
 * @property string|null $document_id
 * @property MemberSex|null $sex
 * @property Carbon|null $birth_date
 * @property string|null $birth_place_city
 * @property string|null $birth_place_state
 * @property string|null $phone
 * @property string|null $landline_phone
 * @property string|null $email
 * @property string|null $address_state
 * @property string|null $address_municipality
 * @property string|null $address_parish
 * @property string|null $address
 * @property MemberEducationLevel|null $education_level
 * @property string|null $profession
 * @property string|null $occupation
 * @property MemberMaritalStatus|null $marital_status
 * @property string|null $spouse_id
 * @property Carbon|null $baptism_date
 * @property string|null $baptism_place
 * @property string|null $baptism_pastor
 * @property Carbon|null $holy_spirit_date
 * @property Carbon|null $joined_date
 * @property MemberStatus|null $status
 * @property string|null $pastor_notes
 * @property string|null $photo_path
 * @property string $search_name Generated by the database from full_name.
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property Carbon|null $deleted_at
 */
#[Fillable([
    'full_name', 'document_type', 'document_id', 'sex', 'birth_date',
    'birth_place_city', 'birth_place_state', 'phone', 'landline_phone', 'email',
    'address_state', 'address_municipality', 'address_parish', 'address',
    'education_level', 'profession', 'occupation', 'marital_status', 'spouse_id',
    'baptism_date', 'baptism_place', 'baptism_pastor', 'holy_spirit_date',
    'joined_date', 'status', 'pastor_notes', 'photo_path',
])]
class Member extends Model
{
    /** @use HasFactory<MemberFactory> */
    use HasFactory, HasUuids, SoftDeletes;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'document_type' => MemberDocumentType::class,
            'sex' => MemberSex::class,
            'education_level' => MemberEducationLevel::class,
            'marital_status' => MemberMaritalStatus::class,
            'status' => MemberStatus::class,
            'birth_date' => 'date',
            'baptism_date' => 'date',
            'holy_spirit_date' => 'date',
            'joined_date' => 'date',
        ];
    }

    /**
     * @return HasMany<MemberChild, $this>
     */
    public function children(): HasMany
    {
        return $this->hasMany(MemberChild::class);
    }

    /**
     * @return HasMany<MemberRole, $this>
     */
    public function roles(): HasMany
    {
        return $this->hasMany(MemberRole::class);
    }

    /**
     * The user account of this member, when they have one.
     *
     * @return HasOne<User, $this>
     */
    public function user(): HasOne
    {
        return $this->hasOne(User::class);
    }

    /**
     * @return BelongsTo<self, $this>
     */
    public function spouse(): BelongsTo
    {
        return $this->belongsTo(self::class, 'spouse_id');
    }

    /**
     * Accent- and case-insensitive substring search on the name. Served by the
     * trigram index on search_name.
     *
     * @param  Builder<self>  $query
     */
    public function scopeSearch(Builder $query, string $term): void
    {
        $term = trim($term);

        if ($term === '') {
            return;
        }

        $escaped = addcslashes($term, '\\%_');

        $query->whereRaw("search_name LIKE '%' || lower(immutable_unaccent(?)) || '%'", [$escaped]);
    }

    /**
     * Default list order: by normalized name, id as the keyset tiebreaker.
     *
     * @param  Builder<self>  $query
     */
    public function scopeOrderedByName(Builder $query): void
    {
        $query->orderBy('search_name')->orderBy('id');
    }
}
